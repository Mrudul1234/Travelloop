export const DEFAULT_PHOTO = 'https://images.unsplash.com/photo-1548013146-72479768bada?w=800&q=80';

export function getCityPhoto(cityName: string = '', stateName: string = ''): string {
  if (!cityName && !stateName) return DEFAULT_PHOTO;
  
  const cityKey = cityName.toLowerCase().trim().replace(/[()]/g, '');
  const stateKey = stateName.toLowerCase().trim();
  
  // 1. Try exact city match
  if (CITY_PHOTOS[cityKey]) return CITY_PHOTOS[cityKey];
  
  // 2. Try partial city match (e.g. "Varanasi (Kashi)" matches "varanasi")
  const cityEntry = Object.entries(CITY_PHOTOS).find(([k]) => 
    cityKey.includes(k) || k.includes(cityKey)
  );
  if (cityEntry) return cityEntry[1];
  
  // 3. Try exact state match
  if (stateKey && STATE_PHOTOS[stateKey]) return STATE_PHOTOS[stateKey];
  
  // 4. Try partial state match
  if (stateKey) {
    const stateEntry = Object.entries(STATE_PHOTOS).find(([k]) => 
      stateKey.includes(k) || k.includes(stateKey)
    );
    if (stateEntry) return stateEntry[1];
  }
  
  // 5. Check if city string contains any known destination
  const containsEntry = Object.entries(CITY_PHOTOS).find(([k]) => 
    cityKey.includes(k)
  );
  if (containsEntry) return containsEntry[1];

  // 6. If city name contains a state name, use that state's photo
  const implicitStateEntry = Object.entries(STATE_PHOTOS).find(([k]) => 
    cityKey.includes(k)
  );
  if (implicitStateEntry) return implicitStateEntry[1];
  
  return DEFAULT_PHOTO;
}
